CREATE TABLE users (
                       user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       user_name VARCHAR(255) NOT NULL,
                       email VARCHAR(255) NOT NULL,
                       role VARCHAR(50) NOT NULL,
                       password VARCHAR(255) NOT NULL,
                       active BOOLEAN NOT NULL,
                       created_at TIMESTAMP NOT NULL
);

CREATE TABLE customers (
                           c_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           company_name VARCHAR(255) NOT NULL,
                           contact_person VARCHAR(255) NOT NULL,
                           email VARCHAR(255) NOT NULL,
                           phone VARCHAR(255),
                           address VARCHAR(255),
                           active BOOLEAN,
                           created_at TIMESTAMP NOT NULL
);

CREATE TABLE sites (
                       site_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       site_name VARCHAR(255) NOT NULL,
                       address VARCHAR(255) NOT NULL,
                       contact_person VARCHAR(255) NOT NULL,
                       phone VARCHAR(255) NOT NULL,
                       active BOOLEAN,
                       customer_id BIGINT NOT NULL,
                       created_at TIMESTAMP NOT NULL,

                       CONSTRAINT fk_site_customer
                           FOREIGN KEY (customer_id)
                               REFERENCES customers(c_id)
);

CREATE TABLE work_orders (
                             workorder_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             title VARCHAR(255) NOT NULL,
                             description TEXT NOT NULL,
                             status VARCHAR(50) NOT NULL,
                             priority VARCHAR(50) NOT NULL,
                             customer_id BIGINT NOT NULL,
                             technician_id BIGINT,
                             created_at TIMESTAMP NOT NULL,
                             scheduled_date TIMESTAMP,
                             completed_date TIMESTAMP,
                             notes TEXT,
                             site_id BIGINT NOT NULL,

                             CONSTRAINT fk_workorder_customer
                                 FOREIGN KEY (customer_id)
                                     REFERENCES customers(c_id),

                             CONSTRAINT fk_workorder_technician
                                 FOREIGN KEY (technician_id)
                                     REFERENCES users(user_id),

                             CONSTRAINT fk_workorder_site
                                 FOREIGN KEY (site_id)
                                     REFERENCES sites(site_id)
);